public class BuiltIn {
    public static void main(String[] args) {
        System.out.println(Math.sqrt(4));   // For Square Root

        System.out.println(Math.cbrt(45));  // For Cube Root

        System.out.print(Math.abs(-47) + " ");  // For Absolute Value
        System.out.println(Math.abs(87));

        System.out.println(Math.floor(4.7));  // For Highest Close value (Floor)
        System.out.println(Math.floor(-7.8));   // -8

        System.out.println(Math.ceil(2.9)); // For Minimum Close Value (Ceiling)
        System.out.println(Math.ceil(-7.8));    // -7

        System.out.println(Math.min(24,45 ));   // Gives Minimum Value
        System.out.println(Math.min(-45,-25));   

        System.out.println(Math.max(24, 45));   // Gives Maximum Value
        System.out.println(Math.max(-45, -25));
    }
}
